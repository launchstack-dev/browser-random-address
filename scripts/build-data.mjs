#!/usr/bin/env node
// Build-time only. This is the one place that touches the network, and its
// output (data/*.js) is committed, so users of the extension never run it.
//
//   node scripts/build-data.mjs names [--first-csv baby-names.csv] [--census names.zip]
//   <NAD csv on stdin> | node scripts/build-data.mjs addresses
// Add --out <dir> to write somewhere other than data/.
//
// See README.md for how to stream the NAD zip into the second form.
import { execFileSync } from 'node:child_process';
import { createInterface } from 'node:readline';
import { writeFileSync, readFileSync, mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { STATES } from '../lib/states.js';
import { resolveColumns, cleanRow, parseLine, Reservoir, finalizeState } from './clean.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const CENSUS_URL = 'https://www2.census.gov/topics/genealogy/2010surnames/names.zip';
// SSA baby names (top 1000 per year and sex, 1880-2008) as mirrored on GitHub; SSA itself blocks scripted downloads.
const FIRST_NAMES_URL = 'https://raw.githubusercontent.com/hadley/data-baby-names/master/baby-names.csv';
const FIRST_YEARS = [1970, 2008];
const TOP_FIRST = 300;
const TOP_LAST = 1000;
const PER_STATE = 1000;
const POOL_PER_STATE = 20000;

const unzipText = (zip, entry) =>
  execFileSync('unzip', ['-p', zip, entry], { maxBuffer: 1 << 30 }).toString('utf8');

function writeModule(file, value, header) {
  writeFileSync(join(arg('out') ?? join(root, 'data'), file), `// ${header}\nexport default ${value};\n`);
}

function arg(name) {
  const i = process.argv.indexOf(`--${name}`);
  return i > 0 ? process.argv[i + 1] : undefined;
}

async function download(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`Download failed (${res.status}): ${url}`);
  return Buffer.from(await res.arrayBuffer());
}

async function buildNames() {
  let census = arg('census');
  if (!census) {
    census = join(mkdtempSync(join(tmpdir(), 'census-')), 'names.zip');
    writeFileSync(census, await download(CENSUS_URL));
  }
  const firstCsv = arg('first-csv');
  const csv = (firstCsv ? readFileSync(firstCsv) : await download(FIRST_NAMES_URL)).toString('utf8');

  // Rows are: year,name,percent,sex. Summing percent across years ranks names by popularity.
  const totals = { boy: new Map(), girl: new Map() };
  for (const line of csv.split('\n').slice(1)) {
    const [year, name, percent, sex] = line.replaceAll('"', '').trim().split(',');
    if (!totals[sex] || year < FIRST_YEARS[0] || year > FIRST_YEARS[1] || !/^[A-Za-z]+$/.test(name)) continue;
    totals[sex].set(name, (totals[sex].get(name) ?? 0) + Number(percent));
  }
  const top = (m) => [...m].sort((a, b) => b[1] - a[1]).slice(0, TOP_FIRST).map(([n]) => n);

  const last = unzipText(census, 'Names_2010Census.csv').split('\n').slice(1)
    .map((l) => l.split(',')).filter(([name, rank]) => /^[A-Z]+$/.test(name) && Number(rank) > 0)
    .slice(0, TOP_LAST).map(([name]) => name);

  const names = { first: { m: top(totals.boy), f: top(totals.girl) }, last };
  writeModule('names.js', JSON.stringify(names),
    `Generated by scripts/build-data.mjs. First names: SSA baby names ${FIRST_YEARS.join('-')}. Surnames: US Census 2010.`);
  console.log(`names: ${names.first.m.length} M, ${names.first.f.length} F, ${names.last.length} surnames`);
}

async function buildAddresses() {
  const rl = createInterface({ input: process.stdin, crlfDelay: Infinity });
  let cols = null;
  const pools = new Map(Object.keys(STATES).map((s) => [s, new Reservoir(POOL_PER_STATE)]));
  let lines = 0;
  let kept = 0;
  for await (const line of rl) {
    const fields = parseLine(line);
    if (!cols) { cols = resolveColumns(fields.map((f) => f.trim())); continue; }
    lines++;
    if (lines % 5_000_000 === 0) console.error(`${lines / 1e6}M rows, ${kept} usable`);
    const row = cleanRow(fields, cols);
    const pool = row && pools.get(row[3]);
    if (!pool) continue;
    kept++;
    pool.add(row);
  }
  const out = {};
  for (const state of Object.keys(STATES)) out[state] = finalizeState(pools.get(state).items, PER_STATE);
  const body = `{\n${Object.entries(out).map(([s, rows]) => `  ${s}: ${JSON.stringify(rows)}`).join(',\n')},\n}`;
  writeModule('addresses.js', body,
    'Generated by scripts/build-data.mjs from the USDOT National Address Database (address points only: no names, no coordinates).');
  console.log(`rows read: ${lines}, usable: ${kept}`);
  for (const [s, rows] of Object.entries(out)) if (rows.length < PER_STATE) console.log(`  ${s}: only ${rows.length}`);
}

const command = process.argv[2];
if (command === 'names') await buildNames();
else if (command === 'addresses') await buildAddresses();
else { console.error('usage: build-data.mjs names|addresses (see header comment)'); process.exit(1); }
